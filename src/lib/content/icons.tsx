export type IconName = keyof typeof ICONS;

export const ICON_NAMES = Object.keys(ICONS) as IconName[];

/** `{ value, label }` pairs for the admin icon picker. */
export const ICON_OPTIONS = ICON_NAMES.map((name) => ({ value: name, label: ICONS[name].label }));

export function isIconName(name: string): name is IconName {
  return Object.prototype.hasOwnProperty.call(ICONS, name);
}

/**
 * Render a registry icon. Color comes from CSS `currentColor` — wrap it in
 * an element with the desired `text-*` color. Unknown names fall back to the
 * box glyph so a typo in content never crashes a page.
 */
export function SiteIcon({
  name,
  size = 24,
  className,
  style,
}: {
  name: string;
  size?: number;
  className?: string;
  style?: CSSProperties;
}) {
  const def: IconDef = isIconName(name) ? ICONS[name] : ICONS.box;
  const cls = [def.className, className].filter(Boolean).join(" ") || undefined;
  if (def.kind === "stroke") {
    return (
      <svg
        width={size}
        height={size}
        viewBox={def.viewBox}
        fill="none"
        stroke="currentColor"
        strokeWidth="1.75"
        strokeLinecap="round"
        strokeLinejoin="round"
        className={cls}
        style={style}
        aria-hidden
      >
        {def.body}
      </svg>
    );
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox={def.viewBox}
      fill="currentColor"
      xmlns="http://www.w3.org/2000/svg"
      className={cls}
      style={style}
      aria-hidden
    >
      {def.body}
    </svg>
  );
}

/**
 * Content lists carry icon NAMES, older call sites may still pass JSX.
 * Accept both so every section can be fed from JSON or from code.
 */
export function renderIcon(icon: ReactNode | string, size: number): ReactNode {
  return typeof icon === "string" ? <SiteIcon name={icon} size={size} /> : icon;
}
